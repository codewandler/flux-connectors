#!/usr/bin/env python3
"""Vendor and normalize Asterisk 22.10.1 ARI from its official public source."""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "specs" / "asterisk"
PINNED_HASHES = TARGET / "upstream.sha256"
NORMALIZER = ROOT / "scripts" / "normalize-asterisk-ari.py"
SOURCE_REPOSITORY = "https://github.com/asterisk/asterisk"
SOURCE_TAG = "22.10.1"
SOURCE_TAG_OBJECT = "4f85d05889cf9fb9c9e2ae44cc3f4a825a74545a"
SOURCE_COMMIT = "f0e408a7b0d829c85bf15fa4b487870a50cb3000"
RAW_BASE = f"https://raw.githubusercontent.com/asterisk/asterisk/{SOURCE_COMMIT}"
DOCUMENTS = (
    "applications.json",
    "asterisk.json",
    "bridges.json",
    "channels.json",
    "deviceStates.json",
    "endpoints.json",
    "events.json",
    "mailboxes.json",
    "playbacks.json",
    "recordings.json",
    "sounds.json",
)
SOURCE_PATHS = (
    "COPYING",
    "resources.json",
    *(f"api-docs/{name}" for name in DOCUMENTS),
)


def fail(message: str) -> None:
    raise SystemExit(f"error: {message}")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def upstream_path(relative: str) -> str:
    if relative == "COPYING":
        return relative
    return f"rest-api/{relative}"


def source_url(relative: str) -> str:
    return f"{RAW_BASE}/{upstream_path(relative)}"


def pinned_hashes() -> dict[str, str]:
    pinned: dict[str, str] = {}
    try:
        lines = PINNED_HASHES.read_text().splitlines()
    except OSError as error:
        fail(f"cannot read pinned hashes at {PINNED_HASHES}: {error}")
    for raw_line in lines:
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        fields = line.split()
        if len(fields) != 2:
            fail(f"malformed pinned hash line: {raw_line!r}")
        digest, relative = fields
        path = PurePosixPath(relative)
        if path.is_absolute() or ".." in path.parts:
            fail(f"unsafe pinned path: {relative!r}")
        if len(digest) != 64 or any(character not in "0123456789abcdef" for character in digest):
            fail(f"invalid SHA-256 for {relative!r}")
        if relative in pinned:
            fail(f"duplicate pinned path: {relative!r}")
        pinned[relative] = digest
    if set(pinned) != set(SOURCE_PATHS):
        fail(
            "pinned source inventory differs; "
            f"missing={sorted(set(SOURCE_PATHS) - set(pinned))}, "
            f"extra={sorted(set(pinned) - set(SOURCE_PATHS))}"
        )
    return pinned


def read_source(relative: str, checkout: Path | None) -> bytes:
    if checkout is not None:
        path = checkout / upstream_path(relative)
        try:
            return path.read_bytes()
        except OSError as error:
            fail(f"cannot read pinned source file {path}: {error}")
    try:
        with urllib.request.urlopen(source_url(relative)) as response:
            return response.read()
    except OSError as error:
        fail(f"cannot fetch {source_url(relative)}: {error}")


def validate_checkout_inventory(checkout: Path) -> None:
    api_dir = checkout / "rest-api" / "api-docs"
    if not api_dir.is_dir():
        fail(f"source checkout has no ARI document directory: {api_dir}")
    actual = {path.name for path in api_dir.iterdir() if path.suffix == ".json"}
    expected = set(DOCUMENTS)
    if actual != expected:
        fail(
            "source checkout ARI document inventory differs; "
            f"missing={sorted(expected - actual)}, extra={sorted(actual - expected)}"
        )


def provenance(stage: Path, normalized: bytes) -> bytes:
    lines = [
        "# Generated by `scripts/vendor-asterisk-ari.py`; re-run the script instead of editing.",
        "# The raw Swagger bytes are the source contract; the OpenAPI file is deterministic derived input.",
        "",
        "version = 1",
        f'source_repository = "{SOURCE_REPOSITORY}"',
        f'source_tag = "{SOURCE_TAG}"',
        f'source_tag_object = "{SOURCE_TAG_OBJECT}"',
        f'source_commit = "{SOURCE_COMMIT}"',
        f'source_url = "{RAW_BASE}"',
        'upstream_license = "GPL-2.0-only"',
        "raw_document_count = 11",
        "source_path_count = 76",
        "source_operation_count = 109",
        "rest_operation_count = 108",
        'deferred_operation_ids = ["events-eventWebsocket"]',
        'normalized_path = "specs/asterisk/ari-22.10.1.openapi.json"',
        f'normalized_sha256 = "{sha256(normalized)}"',
        f"normalized_bytes = {len(normalized)}",
    ]
    for relative in SOURCE_PATHS:
        data = (stage / relative).read_bytes()
        lines.extend(
            [
                "",
                "[[source_files]]",
                f'path = "{relative}"',
                f'source_url = "{source_url(relative)}"',
                f'sha256 = "{sha256(data)}"',
                f"bytes = {len(data)}",
            ]
        )
    return ("\n".join(lines) + "\n").encode()


def expected_output_paths() -> tuple[str, ...]:
    return (
        *SOURCE_PATHS,
        "upstream.sha256",
        "ari-22.10.1.openapi.json",
        "provenance.toml",
    )


def compare_or_write(stage: Path, output: Path, check: bool) -> None:
    api_dir = output / "api-docs"
    if api_dir.is_dir():
        actual = {path.name for path in api_dir.iterdir() if path.suffix == ".json"}
        expected = set(DOCUMENTS)
        if actual != expected:
            fail(
                "target ARI document inventory differs; refusing ambiguous output; "
                f"missing={sorted(expected - actual)}, extra={sorted(actual - expected)}"
            )
    for relative in expected_output_paths():
        source = stage / relative
        target = output / relative
        expected = source.read_bytes()
        if check:
            try:
                actual = target.read_bytes()
            except OSError as error:
                fail(f"cannot check {target}: {error}")
            if actual != expected:
                fail(f"vendored Asterisk output is stale: {target}")
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        temporary = target.with_name(f".{target.name}.tmp")
        temporary.write_bytes(expected)
        os.replace(temporary, target)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        type=Path,
        help=(
            "Asterisk source checkout rooted at COPYING/rest-api; without this option, fetch the "
            "pinned commit from raw.githubusercontent.com"
        ),
    )
    parser.add_argument("--output-dir", type=Path, default=TARGET)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    checkout = args.source_dir.resolve() if args.source_dir else None
    if checkout is not None:
        if not checkout.is_dir():
            fail(f"source checkout does not exist: {checkout}")
        validate_checkout_inventory(checkout)
    pinned = pinned_hashes()

    with tempfile.TemporaryDirectory(prefix="flux-asterisk-ari-") as directory:
        stage = Path(directory) / "asterisk"
        for relative in SOURCE_PATHS:
            data = read_source(relative, checkout)
            actual = sha256(data)
            if actual != pinned[relative]:
                fail(
                    f"pinned SHA-256 mismatch for {relative}: "
                    f"expected {pinned[relative]}, got {actual}"
                )
            destination = stage / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
        shutil.copyfile(PINNED_HASHES, stage / "upstream.sha256")

        normalized_path = stage / "ari-22.10.1.openapi.json"
        result = subprocess.run(
            [
                sys.executable,
                str(NORMALIZER),
                "--source-dir",
                str(stage),
                "--output",
                str(normalized_path),
            ],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode:
            fail(f"normalizer failed: {result.stderr.strip()}")
        normalized = normalized_path.read_bytes()
        (stage / "provenance.toml").write_bytes(provenance(stage, normalized))
        compare_or_write(stage, args.output_dir, args.check)

    action = "checked" if args.check else "vendored"
    print(
        f"{action} Asterisk ARI {SOURCE_TAG} ({SOURCE_COMMIT}): "
        "11 documents, 109 source operations, 108 REST operations, 1 deferred WebSocket"
    )


if __name__ == "__main__":
    main()
