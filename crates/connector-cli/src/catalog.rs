//! Rendering `crates/catalog`'s generated half: one `.flux` file per operation, the Rust table that
//! embeds them, and the index naming every provider's table (C-104).
//!
//! The first two are **per provider** and a scoped build regenerates exactly what it compiled. The
//! index is not — see [`render_index`], which is the whole-catalogue half and is therefore planned
//! by a full run only.
//!
//! `connectors/<provider>.flux` stays the artifact that ships and installs into `~/.flux/flows`.
//! What is generated here is *additional* — the catalog's unit — and it is the same text: an
//! operation's rendering is byte for byte what [`crate::seam::module`] concatenates into the
//! provider module, with no header of its own, so the two can never describe different requests.
//! `crates/connector-cli/tests/catalog_artifacts.rs` pins that.
//!
//! # Why the table is Rust rather than data
//!
//! The catalog crate has **no dependencies**, and that is a feature a consumer feels: `cargo add
//! connector-catalog` costs them one crate and no runtime work. Emitting JSON or TOML alongside the
//! Flux would mean the catalog either grows a parser dependency or parses on first use behind a
//! lock — both to reconstruct, at runtime, a table already known at build time. A generated `static`
//! is that table, laid out by the compiler in `.rodata`.
//!
//! Note what this is *not*: it is not the "no homegrown DSL" or "never string-template Flux" rule
//! being bent. Not one byte of **Flux** is assembled here. The Flux comes from
//! `connector_flux::emit_operation`, which builds real `flux_lang` AST nodes and runs flux-lang's
//! own formatter over them; this module only quotes that text into an `include_str!`.
//!
//! # Two properties this rendering must hold, and how each is held
//!
//! **Deterministic.** Equal inputs produce byte-identical output — the whole reason a rebuild
//! writes nothing. Everything below is a function of the IR alone, walked in the IR's own order,
//! with no map iteration and no timestamp.
//!
//! **rustfmt-stable.** The generated file is inside `cargo fmt --all --check`'s reach, so text
//! rustfmt would rewrite fails the gate. Rather than chase rustfmt's layout from a string builder —
//! a fixed point that would have to be rediscovered on every toolchain bump — each generated item
//! carries `#[rustfmt::skip]`, which is exactly the tool attribute's purpose. The `.flux` half is
//! held to flux-lang's formatter instead, by the emitter, and that fixed point *is* asserted
//! (`connector-flux`'s `shipped_modules.rs`).

use std::collections::BTreeMap;

use anyhow::{bail, Context, Result};
use connector_spec::{AuthScheme, Connector, Idempotency, Operation, Risk};

/// One operation's `.flux` rendering, on its way to `crates/catalog/ops/<provider>/<id>.flux`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OperationRendering {
    /// The operation id — the file stem, and the catalog's key.
    pub id: String,
    /// The formatted `op` declaration, exactly as the provider module carries it.
    pub source: String,
}

/// Render `crates/catalog/src/generated/<provider>.rs`: the provider's identity, and one
/// [`catalog::Operation`](../../catalog/src/lib.rs) entry per rendering.
///
/// `renderings` is passed in rather than recomputed so that the embedded text and the provider
/// module are emitted **once**, from one call to `connector_flux::emit_operation` per operation.
/// Emitting twice would make "the catalog agrees with the module" a coincidence rather than a
/// structural fact.
pub fn render(connector: &Connector, renderings: &[OperationRendering]) -> Result<String> {
    let mut out = format!(
        "// Generated by {} — do not edit.\n\
         // Provider: {}\n\
         // Regenerate with `flux-connectors build`.\n\
         //\n\
         // The `include_str!` paths point at `crates/catalog/ops/{}/`, which the same build wrote.\n\n",
        crate::seam::generator(),
        connector.id,
        connector.id,
    );

    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub(crate) static PROVIDER: crate::Provider = crate::Provider {\n");
    out.push_str(&format!("    id: {},\n", string(&connector.id)));
    out.push_str(&format!("    vendor: {},\n", string(&connector.vendor)));
    out.push_str(&format!(
        "    description: {},\n",
        string(&connector.description)
    ));
    out.push_str(&format!(
        "    authority: {},\n",
        option_string(connector.authority.as_deref())
    ));
    out.push_str(&format!("    runtime: {},\n", runtime(connector.runtime)));
    out.push_str(&format!("    base_url: {},\n", string(&connector.base_url)));
    out.push_str("    auth: AUTH,\n");
    out.push_str("    operations: OPERATIONS,\n");
    out.push_str("    config: CONFIG,\n");
    out.push_str(&format!(
        "    verify: {},\n",
        option_string(connector.verify.as_deref())
    ));
    out.push_str("    events: EVENTS,\n");
    out.push_str("    channels: CHANNELS,\n");
    out.push_str("    config_choices: CONFIG_CHOICES,\n");
    out.push_str("};\n\n");

    out.push_str(&render_auth(connector)?);
    out.push_str(&render_config(connector)?);
    out.push_str(&render_events(connector)?);
    out.push_str(&render_channels(connector)?);
    out.push_str(&render_config_choices(connector));

    out.push_str("#[rustfmt::skip]\n");
    out.push_str("static OPERATIONS: &[crate::Operation] = &[\n");
    for rendering in renderings {
        let operation = operation_for(connector, &rendering.id)?;
        // Per operation, through its service: a multi-service provider reaches a different host per
        // service, and the union would be a wider egress claim than any single call makes (C-49).
        let host = host_of(connector.base_url_of(&operation.service))?;
        out.push_str(&entry(connector, operation, host));
    }
    out.push_str("];\n");

    Ok(out)
}

/// Render `crates/catalog/src/generated.rs`: one `mod` line and one `PROVIDERS` entry per provider
/// (C-104).
///
/// `providers` is the **whole** shipped set, in discovery order — which is sorted, and is the order
/// `catalog::providers()` publishes. This is the one file in the catalog crate that is a function of
/// every provider at once rather than of one, so [`crate::pipeline::plan_selected`] plans it only on
/// a full run, exactly as it plans `catalog.json` only on a full run. A `--provider` run would have
/// to render an index naming one provider and silently dropping the rest.
///
/// Until C-104 the file was hand-written for that reason, and the cost was structural rather than
/// cosmetic: every provider story appended two lines to it, so any two provider stories conflicted
/// and the fleet shipped one connector at a time. Generating it under the full-run rule is what makes
/// two implementors' write sets disjoint.
pub fn render_index(providers: &[String]) -> Result<String> {
    let idents = providers
        .iter()
        .map(|provider| module_ident(provider))
        .collect::<Result<Vec<_>>>()?;

    let mut out = format!(
        "//! The generated catalog data, one module per provider.\n\
         //!\n\
         //! Generated by {} — do not edit. Regenerate with `flux-connectors build`.\n\
         //!\n\
         //! **A whole-catalogue artifact**, and therefore written by a *full* build only: an index\n\
         //! rendered from `build --provider zendesk` would name one provider and silently drop the\n\
         //! rest. `web/public/catalog.json` follows the same rule for the same reason\n\
         //! (`docs/designs/catalog-json.md`). The corollary is the point of C-104 — a provider-scoped\n\
         //! build writes only that provider's own files, so provider work fans out instead of\n\
         //! serialising on this one file.\n\
         //!\n\
         //! `crates/catalog/tests/embedded_operations.rs` holds this list against `providers/`, and\n\
         //! `crates/connector-cli/tests/catalog_artifacts.rs` holds the whole tree to being a fixed\n\
         //! point of a build, so a stale index is loud rather than silent.\n\n",
        crate::seam::generator(),
    );

    for ident in &idents {
        out.push_str(&format!("pub(crate) mod {ident};\n"));
    }

    out.push_str("\nuse crate::Provider;\n\n");
    out.push_str(
        "/// Every provider, ordered by id — the order [`crate::providers`] publishes and the order the\n\
         /// catalog's flat listing walks.\n",
    );
    // `#[rustfmt::skip]` for the same reason every other generated item here carries it: the file is
    // inside `cargo fmt --all --check`'s reach, and one provider would let rustfmt collapse the
    // slice onto a single line while seventeen would not. Pinning the layout is cheaper than
    // rediscovering rustfmt's fixed point on every toolchain bump.
    out.push_str("#[rustfmt::skip]\n");
    out.push_str("pub(crate) static PROVIDERS: &[&Provider] = &[\n");
    for ident in &idents {
        out.push_str(&format!("    &{ident}::PROVIDER,\n"));
    }
    out.push_str("];\n");

    Ok(out)
}

/// Every lowercase Rust keyword that `mod <name>;` rejects.
///
/// **Checked against rustc rather than written from memory**, which is how `union` came to be absent:
/// it is a *weak* keyword and `mod union {}` compiles, so refusing or escaping it would be wrong. The
/// probe is `mod <candidate> {}` for each of the strict and reserved keyword lists; anything rustc
/// answers with "expected identifier, found (reserved) keyword" is here.
///
/// `Self` is the one keyword deliberately missing: it is uppercase, and a provider name carrying an
/// uppercase letter is already refused by the character rule below.
const RUST_KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate",
    "do", "dyn", "else", "enum", "extern", "false", "final", "fn", "for", "if", "impl", "in",
    "let", "loop", "macro", "match", "mod", "move", "mut", "override", "priv", "pub", "ref",
    "return", "self", "static", "struct", "super", "trait", "true", "try", "type", "typeof",
    "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

/// The three keywords a raw identifier cannot rescue — `r#crate`, `r#self` and `r#super` are each
/// their own error. Verified the same way as [`RUST_KEYWORDS`].
const UNESCAPABLE_KEYWORDS: &[&str] = &["crate", "self", "super"];

/// The token that names `provider`'s module: the name itself, or `r#name` when it is a keyword.
///
/// `providers/` admits `-` in a file stem — correct everywhere else a provider name goes, since it
/// becomes the artifact file name and the op-id prefix — but `pub(crate) mod google-ads;` does not
/// parse. While the index was hand-written that compile error landed on the human writing the line;
/// generated, it would ship a `crates/catalog` that does not build from an input that looks entirely
/// ordinary.
///
/// **A keyword is escaped rather than refused, and that is a deliberate difference.** `box.com` is
/// squarely inside the charter, and `mod box;` is a compile error — but the fix costs nothing a user
/// can see: `mod r#box;` resolves to the same `generated/box.rs` the build already writes, and the
/// provider id stays `box` in every address, file name and catalogue row. Refusing would force
/// `providers/boxcom.toml` instead, which changes the op-id prefix and the installable artifact
/// name — a published address rewritten to work around a detail of one generated file, which
/// AGENTS.md's "an address, once published, is not reused" exists to prevent.
///
/// What is still refused is what cannot be expressed at all: a name outside the identifier
/// character set, and the three keywords no `r#` accepts.
fn module_ident(provider: &str) -> Result<String> {
    let mut chars = provider.chars();
    let valid = match chars.next() {
        Some(first) if first.is_ascii_lowercase() || first == '_' => {
            chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        }
        _ => false,
    };
    if !valid || provider == "_" {
        bail!(
            "provider `{provider}` cannot name a Rust module, so `crates/catalog/src/generated.rs` \
             would not compile: rename it to lowercase ASCII letters, digits and `_` (a `-` is fine \
             everywhere else a provider name goes, but not here)"
        );
    }
    if UNESCAPABLE_KEYWORDS.contains(&provider) {
        bail!(
            "provider `{provider}` cannot name a Rust module: it is one of the three keywords a raw \
             identifier cannot rescue either, so neither `mod {provider};` nor `mod r#{provider};` \
             compiles. Rename the provider file"
        );
    }
    if RUST_KEYWORDS.contains(&provider) {
        // `mod r#box;` still resolves to `generated/box.rs`, so nothing outside this file moves.
        return Ok(format!("r#{provider}"));
    }
    Ok(provider.to_string())
}

/// The operation a rendering describes — **and the refusal that keeps the third member kind out of
/// every emitted artifact** (C-83).
///
/// Both catalogue backends resolve a rendering through this one function, the same way both share
/// [`credential_mechanisms`] and [`host_of`], so neither can be talked into publishing something the
/// other refuses.
///
/// # Why an event gets its own error
///
/// A rendering whose id names nothing is a bug. A rendering whose id names an **event or a channel
/// binding** is a specific bug with a specific name, and it is the one `AGENTS.md` calls out: *"the
/// tempting wrong output is an event dressed up as a pollable op."* Both kinds are emitted into no
/// Flux module at all — flux lifts `op` declarations only, while `channel` and `trigger` are Program
/// members an operator writes — so a rendering for one could only have been produced by an emitter
/// that decided to synthesise a poll loop, which is this repository writing a runtime.
///
/// Reported separately because the two have opposite fixes. "No such operation" says a name is
/// wrong; this says the name is *right* and the pipeline is wrong, and a generic message would send
/// the reader looking for a typo that is not there.
pub(crate) fn operation_for<'a>(connector: &'a Connector, id: &str) -> Result<&'a Operation> {
    if let Some(operation) = connector.operation(id) {
        return Ok(operation);
    }
    if let Some(kind) = inbound_member_kind(connector, id) {
        bail!(
            "connector `{}`: `{id}` is {kind}, not an operation, so there is no Flux to publish for \
             it. A binding declares and never installs: it reaches the manifest and the catalogue \
             and is emitted into no module, because flux lifts `op` declarations only. Emitting one \
             would be an event dressed up as a pollable op, which this pipeline refuses rather than \
             degrades to",
            connector.id
        );
    }
    bail!(
        "connector `{}` has no operation `{id}` to describe",
        connector.id
    );
}

/// Which inbound member kind `name` denotes, or `None` when it denotes neither.
///
/// The three member kinds share one namespace per service, so at most one of these matches.
fn inbound_member_kind(connector: &Connector, name: &str) -> Option<&'static str> {
    if connector.event(name).is_some() {
        return Some("an event");
    }
    if connector.channel(name).is_some() {
        return Some("a channel binding");
    }
    None
}

/// One `crate::Operation { … }` literal.
fn entry(connector: &Connector, operation: &Operation, host: &str) -> String {
    let mut out = String::from("    crate::Operation {\n");
    out.push_str(&format!("        id: {},\n", string(&operation.id)));
    out.push_str(&format!("        provider: {},\n", string(&connector.id)));
    // The service, carried rather than elided (C-197). It is what makes `hosts` below legible — a
    // multi-service provider reaches a different host per service — and it is the key a consumer
    // needs in order to keep two services' same-named configuration variables apart. The reserved
    // `default` is written out here: elision is an *address* rule, and a consumer grouping by
    // service unconditionally needs a name in every row.
    out.push_str(&format!(
        "        service: {},\n",
        string(&operation.service)
    ));
    out.push_str(&format!(
        "        direction: crate::OperationDirection::{},\n",
        match operation.direction {
            connector_spec::OperationDirection::Read => "Read",
            connector_spec::OperationDirection::Write => "Write",
        }
    ));
    out.push_str(&format!(
        "        description: {},\n",
        string(&operation.description)
    ));
    out.push_str(&format!("        risk: {},\n", risk(operation.risk)));
    out.push_str(&format!(
        "        idempotency: {},\n",
        idempotency(operation.idempotency)
    ));
    out.push_str(&format!(
        "        semantic_effects: {},\n",
        semantic_effects(operation)
    ));
    out.push_str(&format!(
        "        credentials: {},\n",
        credentials(connector, operation)
    ));
    // Why that list is what it is — the distinction an empty slice cannot make (C-235). Emitted
    // beside the list rather than folded into it: `Operation::credentials`'s type is the catalog
    // crate's published API, and a consumer already matching on the mechanism shape must keep
    // working.
    out.push_str(&format!(
        "        credential_requirement: {},\n",
        credential_requirement(connector, operation)
    ));
    out.push_str(&format!("        hosts: &[{}],\n", string(host)));
    // Escaped like every other literal here rather than interpolated raw. An id that reaches this
    // point is already constrained — the emitter refuses anything Flux cannot declare — but the
    // path is still a string literal, and one unescaped character in it is a generated file that
    // does not compile for a reason nobody can see in the provider TOML.
    out.push_str(&format!(
        "        flux: include_str!({}),\n",
        string(&format!(
            "../../ops/{}/{}.{}",
            connector.id,
            operation.id,
            crate::workspace::MODULE_EXT
        ))
    ));
    out.push_str("    },\n");
    out
}

/// The operation's credentials as alternatives (OR) of mechanisms (AND) — the IR's own shape,
/// carried across rather than flattened.
///
/// Flattening is the thing to avoid: babelforce's `accessId` + `accessToken` travel **together** on
/// one request and are an alternative to OAuth2, so a flat list of three names would tell a caller
/// that any one of them authenticates, which is false in both directions.
fn credentials(connector: &Connector, operation: &Operation) -> String {
    let mechanisms = credential_mechanisms(connector, operation);
    let rendered: Vec<String> = mechanisms
        .iter()
        .map(|mechanism| {
            let names: Vec<String> = mechanism.iter().map(|name| string(name)).collect();
            format!("&[{}]", names.join(", "))
        })
        .collect();
    format!("&[{}]", rendered.join(", "))
}

/// The operation's credentials as alternatives (OR) of mechanisms (AND), as plain data.
///
/// The one walk both catalogue backends share: this module quotes it into Rust literals and
/// [`crate::site`] serializes it into JSON, so the crate cannot ship a `catalog.json` that
/// disagrees with `crates/catalog` about what authenticates an operation.
///
/// Resolved through [`Connector::effective_auth`], never by reading `Operation::auth` directly: an
/// operation that declares nothing inherits the connector default, and one that declares an
/// explicit empty list inherits nothing.
pub(crate) fn credential_mechanisms<'a>(
    connector: &'a Connector,
    operation: &'a Operation,
) -> Vec<Vec<&'a str>> {
    connector
        .effective_auth(operation)
        .iter()
        .map(|mechanism| mechanism.iter().map(String::as_str).collect())
        .collect()
}

/// `crate::status::CredentialRequirement` as the catalog's own mirror of it — C-235.
///
/// Exhaustive for the same reason [`risk`] is, and with the same two-sided guarantee: a state added
/// to the classification is a compile error here until someone names its counterpart, and naming a
/// counterpart `catalog::CredentialRequirement` does not have fails to compile in `crates/catalog`.
///
/// The classification itself lives in [`crate::status`], which is also what turns it into
/// `catalog.json`'s [`Issue`](crate::status::Issue) or [`Note`](crate::status::Note). One
/// derivation, two renderings — the published catalogue and the embedded one cannot answer this
/// question differently, which is the drift C-206 and C-212 each closed one surface at a time.
fn credential_requirement(connector: &Connector, operation: &Operation) -> &'static str {
    use crate::status::CredentialRequirement;
    match crate::status::credential_requirement(connector, operation) {
        CredentialRequirement::Declared => "crate::CredentialRequirement::Declared",
        CredentialRequirement::NoneRequired => "crate::CredentialRequirement::NoneRequired",
        CredentialRequirement::Withheld => "crate::CredentialRequirement::Withheld",
    }
}

/// The host a call reaches, taken from the connector's base URL with its templating intact.
///
/// `https://{subdomain}.zendesk.com` yields `{subdomain}.zendesk.com`: the tenant is the operator's
/// to choose, and substituting a placeholder here would invent one. A caller reads this to decide
/// whether their egress policy admits the call, and a pattern is the honest answer to that.
///
/// C-10 replaces this with the manifest's real `http_hosts` allowlist, which is why the catalog
/// field is a slice: today every operation reaches exactly the connector's own host.
///
/// Shared with [`crate::site`] so that `catalog.json` and `crates/catalog` name the same host — two
/// answers to "which host does this reach?" would be one answer too many.
pub(crate) fn host_of(base_url: &str) -> Result<&str> {
    let after_scheme = base_url
        .split_once("://")
        .map_or(base_url, |(_scheme, rest)| rest);
    let host = after_scheme
        .split(['/', '?', '#'])
        .next()
        .unwrap_or(after_scheme);
    if host.is_empty() {
        bail!("base URL `{base_url}` names no host, so nothing can say which host it reaches");
    }
    Ok(host)
}

/// The connector's `AUTH` table: one `crate::Credential` per declared credential (C-116).
///
/// **This is a declaration, never a value.** [`string`] quotes a credential *name*, a path leaf, a
/// header name, a placement prefix and environment-variable *keys*. That it cannot quote a value is
/// structural rather than careful: `connector_spec::AuthMethod` has no field one could live in — `env`
/// and `user_env` are key lists, and `user_suffix` is Zendesk's public `/token` marker
/// (`crates/connector-spec/src/auth.rs`) — so an emitter that wanted to leak a credential would have
/// to change the IR first, which is a reviewed change in a different crate.
///
/// It exists because the Tool pack assembles auth in Rust — the `Bearer` prefix, the basic-auth
/// base64, the query placement — and it cannot assemble what it has not been told. Until this, the
/// catalogue named the credentials an operation required and said nothing about how any of them
/// reached the wire, so the only thing a consumer could do with a credential name was ignore it.
fn render_auth(connector: &Connector) -> Result<String> {
    let mut out = String::from("#[rustfmt::skip]\n");
    out.push_str("static AUTH: &[crate::Credential] = &[\n");
    for method in &connector.auth {
        // The leaf of the credential's address. Derived by the type that owns the rule rather than
        // by stripping a prefix here: a name whose prefix disagrees with the connector id would
        // otherwise render a plausible path under the wrong vendor.
        let leaf = connector
            .local_credential_name(&method.name)
            .with_context(|| {
                format!("connector `{}`: credential `{}`", connector.id, method.name)
            })?;
        out.push_str("    crate::Credential {\n");
        out.push_str(&format!("        name: {},\n", string(&method.name)));
        out.push_str(&format!("        leaf: {},\n", string(leaf)));
        out.push_str(&format!(
            "        acquire: {},\n",
            acquisition(connector, method)
        ));
        out.push_str(&format!("        place: {},\n", placement(&method.scheme)));
        // Emitted even when unreviewed, deliberately. `Unstated` is a state a host must be able to
        // see — "nobody checked" and "this is an app token" call for different behaviour — so it is
        // published rather than skipped the way the *manifest* skips it to keep artifacts stable.
        out.push_str(&format!("        subject: {},\n", subject(method.subject)));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");
    Ok(out)
}

fn render_config(connector: &Connector) -> Result<String> {
    let mut out = String::from("#[rustfmt::skip]\nstatic CONFIG: &[crate::ConfigField] = &[\n");
    for field in &connector.config {
        let also_binds = field
            .also_binds
            .iter()
            .map(|binds| string(binds))
            .collect::<Vec<_>>()
            .join(", ");
        let also_services = field
            .also_services
            .iter()
            .map(|service| string(service))
            .collect::<Vec<_>>()
            .join(", ");
        let declaration = serde_json::to_string(field)?;
        out.push_str("    crate::ConfigField {\n");
        out.push_str(&format!("        name: {},\n", string(&field.name)));
        out.push_str(&format!("        service: {},\n", string(&field.service)));
        out.push_str(&format!("        label: {},\n", string(&field.label)));
        out.push_str(&format!("        help: {},\n", string(&field.help)));
        out.push_str(&format!(
            "        example: {},\n",
            option_string(field.example.as_deref())
        ));
        out.push_str(&format!(
            "        format: {},\n",
            string(field.format.word())
        ));
        out.push_str(&format!("        required: {},\n", field.required));
        out.push_str(&format!(
            "        default: {},\n",
            option_string(field.default.as_deref())
        ));
        out.push_str(&format!(
            "        approval: {},\n",
            approval(field.approval)
        ));
        out.push_str(&format!("        secret: {},\n", field.secret));
        out.push_str(&format!(
            "        docs_url: {},\n",
            option_string(field.docs_url.as_deref())
        ));
        out.push_str(&format!("        binds: {},\n", string(&field.binds)));
        out.push_str(&format!("        also_binds: &[{also_binds}],\n"));
        out.push_str(&format!("        also_services: &[{also_services}],\n"));
        out.push_str(&format!(
            "        declaration_json: {},\n",
            string(&declaration)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");
    Ok(out)
}

fn render_events(connector: &Connector) -> Result<String> {
    let mut out = String::from("#[rustfmt::skip]\nstatic EVENTS: &[crate::Event] = &[\n");
    for event in &connector.events {
        let schema = event
            .schema
            .as_ref()
            .map(serde_json::to_string)
            .transpose()?;
        let declaration = serde_json::to_string(event)?;
        out.push_str("    crate::Event {\n");
        out.push_str(&format!("        name: {},\n", string(&event.name)));
        out.push_str(&format!("        service: {},\n", string(&event.service)));
        out.push_str(&format!(
            "        description: {},\n",
            string(&event.description)
        ));
        out.push_str(&format!(
            "        wire_value: {},\n",
            option_string(event.wire_value.as_deref())
        ));
        out.push_str(&format!("        default: {},\n", event.default));
        out.push_str(&format!("        group: {},\n", string(&event.group)));
        out.push_str(&format!(
            "        schema: {},\n",
            option_string(schema.as_deref())
        ));
        out.push_str(&format!(
            "        declaration_json: {},\n",
            string(&declaration)
        ));
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");
    Ok(out)
}

fn render_pairs(values: &BTreeMap<String, String>) -> String {
    values
        .iter()
        .map(|(name, value)| {
            format!(
                "crate::Pair {{ name: {}, value: {} }}",
                string(name),
                string(value)
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn render_requirements(requirements: &[connector_spec::AuthRequirement]) -> String {
    let alternatives = requirements
        .iter()
        .map(|requirement| {
            let names = requirement
                .iter()
                .map(|name| string(name))
                .collect::<Vec<_>>();
            format!("&[{}]", names.join(", "))
        })
        .collect::<Vec<_>>();
    format!("&[{}]", alternatives.join(", "))
}

fn render_selector(selector: &connector_spec::Selector) -> String {
    let source = match selector.source {
        connector_spec::FieldSource::Header => "header",
        connector_spec::FieldSource::Body => "body",
    };
    format!(
        "crate::Selector {{ source: {}, name: {} }}",
        string(source),
        string(&selector.name)
    )
}

