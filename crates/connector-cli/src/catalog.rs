    fn ids(names: &[&str]) -> Vec<String> {
        names.iter().map(|name| name.to_string()).collect()
    }

    /// The index names every provider it was given, in the order it was given them — which is
    /// discovery order, which is sorted. A `PROVIDERS` slice that did not match the `mod` lines
    /// would compile only by accident.
    #[test]
    fn the_index_names_every_provider_once() {
        let rendered = render_index(&ids(&["acme", "beacon"])).unwrap();
        for provider in ["acme", "beacon"] {
            assert_eq!(
                rendered
                    .matches(&format!("pub(crate) mod {provider};"))
                    .count(),
                1,
                "{rendered}"
            );
            assert_eq!(
                rendered.matches(&format!("&{provider}::PROVIDER,")).count(),
                1,
                "{rendered}"
            );
        }
        assert!(rendered.find("mod acme").unwrap() < rendered.find("mod beacon").unwrap());
    }

    #[test]
