/// **The closed sets a connector's configuration fields declare** — C-225.
///
/// Only the fields that *have* one, so the common connector emits an empty slice and the diff of a
/// provider adopting a set is one block. This is not the whole configuration surface: labels, help,
/// `binds` and the derived level are C-87's, and this publishes exactly the part a closed set is
/// worthless without. A renderer that cannot see the choices draws a text box, which is the state
/// the story exists to leave.
///
/// The row is keyed by `(service, kind, name)` — the same address `connector-pack`'s configuration
/// port stores a value under — so a consumer joins on it without re-parsing `binds`. A field whose
/// binding is malformed contributes nothing, which cannot happen on a loaded connector: `binds` is
/// validated at load, and this runs on the IR.
fn render_config_choices(connector: &Connector) -> String {
    let mut out = String::from("#[rustfmt::skip]\n");
    out.push_str("static CONFIG_CHOICES: &[crate::ConfigChoices] = &[\n");
    for field in &connector.config {
        let Some(binding) = field.binding().filter(|_| field.is_closed()) else {
            continue;
        };
        out.push_str("    crate::ConfigChoices {\n");
        out.push_str(&format!("        service: {},\n", string(&field.service)));
        out.push_str(&format!("        field: {},\n", string(&field.name)));
        out.push_str(&format!("        label: {},\n", string(&field.label)));
        out.push_str(&format!("        kind: {},\n", string(binding.kind())));
        out.push_str(&format!("        name: {},\n", string(binding.target())));
        out.push_str("        choices: &[\n");
        for choice in &field.choices {
            out.push_str(&format!(
                "            crate::Choice {{ value: {}, label: {} }},\n",
                string(&choice.value),
                string(&choice.label)
            ));
        }
        out.push_str("        ],\n");
        out.push_str("    },\n");
    }
    out.push_str("];\n\n");
    out
}

/// The acquisition axis: how stored material becomes the value that is placed.
///
/// `Basic` is the only scheme that composes anything, and it composes the **user** half — which is
/// config rather than a gated secret, so it resolves from declared environment variables and never
/// from the secret store.
///
/// # The minting join (C-136)
///
/// One answer on this axis is not a property of the credential's own declaration at all: a
/// credential minted by one of this connector's operations is `Acquisition::Minted`, and the two
/// facts it carries — which operation, and where in that operation's answer the secret arrives —
/// are stated in the `[[operations]]` block rather than in `[[auth]]`. So this reads the whole
/// connector and joins the two sides by credential name.
///
/// The loader has already refused every arrangement that would make the join ambiguous or
/// unresolvable: a `produces_credential` naming a credential no `[[auth]]` block declares, and two
/// operations minting one credential. So the `find` below is a lookup, not a search with a
/// tie-break — and `Minted` wins over the scheme-derived answer because a minted credential's
/// *placement* is unaffected by it (`Bearer` stays `Bearer`); what changes is only the provenance.
fn acquisition(connector: &Connector, method: &connector_spec::AuthMethod) -> String {
    // OAuth2 is answered first, and the loader has already refused the one arrangement where that
    // ordering could matter: a credential declaring `[auth.oauth2]` *and* named by an operation's
    // `produces_credential` states two contradictory acquisitions, and is refused rather than
    // silently resolved here (C-525). So this is a lookup, not a precedence rule doing real work.
    if let Some(oauth2) = &method.oauth2 {
        return oauth2_acquisition(oauth2);
    }

    if let Some((operation, produced)) = connector.operations.iter().find_map(|operation| {
        operation
            .produces_credential
            .as_ref()
            .filter(|produced| produced.credential == method.name)
            .map(|produced| (operation, produced))
    }) {
        return format!(
            "crate::Acquisition::Minted {{ by: {}, from: {} }}",
            string(&operation.id),
            string(&produced.secret)
        );
    }

    match method.scheme {
        AuthScheme::Basic => format!(
            "crate::Acquisition::BasicJoin {{ user_env: &[{}], user_suffix: {} }}",
            method
                .user_env
                .iter()
                .map(|key| string(key))
                .collect::<Vec<_>>()
                .join(", "),
            string(method.user_suffix.as_deref().unwrap_or_default())
        ),
        _ => "crate::Acquisition::Static".to_string(),
    }
}

/// The subject axis: whose authority the credential carries (C-528).
///
/// Exhaustive, for the reason [`placement`] is. There are only three answers and one of them means
/// "unreviewed"; a catch-all arm would map a fourth to whichever neighbour was listed last, and on
/// this axis the wrong neighbour is either an over-grant or a silent failure.
fn subject(subject: connector_spec::Subject) -> &'static str {
    match subject {
        connector_spec::Subject::Unstated => "crate::Subject::Unstated",
        connector_spec::Subject::App => "crate::Subject::App",
        connector_spec::Subject::User => "crate::Subject::User",
    }
}

/// The OAuth2 acquisition, rendered as a `&'static` the catalogue can hold (C-525).
///
/// `&crate::OAuth2 { … }` is a borrow of a temporary, which is legal here for one specific reason:
/// every field is a constant with no `Drop` and no interior mutability, so const promotion lifts it
/// to `'static` in the `static AUTH` initializer. A field that ever stopped being const would fail
/// to compile rather than silently allocate — which is the property that keeps the catalogue
/// dependency-free.
///
/// **Nothing here can carry a value.** `client_id` is public by specification; the scopes, paths and
/// grants are vendor facts. The client secret is a `[[config]]` binding, resolved by the host from
/// its own store, and there is no field on `OAuth2Spec` it could travel in.
fn oauth2_acquisition(spec: &connector_spec::OAuth2Spec) -> String {
    let scopes = spec
        .scopes
        .iter()
        .map(|scope| string(scope))
        .collect::<Vec<_>>()
        .join(", ");
    let grants = spec
        .grants
        .iter()
        .map(|grant| {
            // Exhaustive, for the reason `placement` is: a grant mapped to the wrong variant runs
            // the wrong flow, and a catch-all arm is how a new one gets mapped to a plausible
            // neighbour instead of failing the build.
            let variant = match grant {
                connector_spec::OAuthGrant::AuthorizationCode => "AuthorizationCode",
                connector_spec::OAuthGrant::Password => "Password",
                connector_spec::OAuthGrant::RefreshToken => "RefreshToken",
                connector_spec::OAuthGrant::ClientCredentials => "ClientCredentials",
            };
            format!("crate::OAuthGrant::{variant}")
        })
        .collect::<Vec<_>>()
        .join(", ");
    let redirect = match &spec.redirect {
        Some(redirect) => format!(
            "Some(crate::OAuthRedirect {{ port: {}, path: {} }})",
            redirect.port,
            string(&redirect.path)
        ),
        None => "None".to_string(),
    };

    format!(
        "crate::Acquisition::OAuth2(&crate::OAuth2 {{ endpoint: {}, authorize_path: {}, \
         token_path: {}, client_id: {}, scopes: &[{scopes}], grants: &[{grants}], \
         redirect: {redirect} }})",
        string(&spec.endpoint),
        string(&spec.authorize_path),
        string(&spec.token_path),
        string(&spec.client_id),
    )
}

/// The placement axis: where the value goes on the request.
///
/// An exhaustive match, for the reason [`risk`] is one — and with more at stake. A scheme this did
/// not recognise would have to become *some* placement, and every wrong answer either sends a
/// credential where the vendor does not read it or sends it somewhere it should never go at all.
///
/// The `prefix` is what makes this a mapping rather than a translation table: `Bearer` and `Basic`
/// differ from a raw-value header only by the literal text in front of the value.
pub(crate) fn placement(scheme: &AuthScheme) -> String {
    match scheme {
        AuthScheme::Bearer => {
            "crate::Placement::Header { name: \"Authorization\", prefix: \"Bearer \" }".to_string()
        }
        AuthScheme::Basic => {
            "crate::Placement::Header { name: \"Authorization\", prefix: \"Basic \" }".to_string()
        }
        // The declared prefix, and the reason this arm reads like the two above it: `Bearer ` and a
        // vendor's `SSWS ` differ only in who wrote the literal. An empty prefix — every shipped
        // `header` credential before C-184 — emits exactly the string this arm emitted when it was
        // hard-coded, which is what keeps the committed catalogue byte-identical.
        AuthScheme::Header { name, prefix } => format!(
            "crate::Placement::Header {{ name: {}, prefix: {} }}",
            string(name),
            string(prefix)
        ),
        AuthScheme::Query { name } => {
            format!("crate::Placement::Query {{ name: {} }}", string(name))
        }
        // The one scheme with no outgoing answer: it verifies bytes that arrived. Carried into the
        // catalogue rather than dropped, so that one namespace still covers both directions and a
        // consumer can *refuse* to spend it on a request rather than never having heard of it.
        AuthScheme::Signing => "crate::Placement::Inbound".to_string(),
    }
}

/// A Rust `Option<&'static str>` literal for an optional declared value.
fn option_string(value: Option<&str>) -> String {
    match value {
        Some(value) => format!("Some({})", string(value)),
        None => "None".to_string(),
    }
}

