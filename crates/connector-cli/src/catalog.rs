/// Semantic effects stay string data in the dependency-free catalogue, using the exact Flux tags
/// the IR validated rather than a second enum consumers would have to translate.
fn semantic_effects(operation: &Operation) -> String {
    let values = operation
        .semantic_effects
        .iter()
        .map(|effect| string(effect.tag()))
        .collect::<Vec<_>>()
        .join(", ");
    format!("&[{values}]")
}

/// A Rust string literal for `value`.
///
/// Escaping rather than a raw literal: a raw string would have to pick a hash count no content
/// collides with, and a description carrying `"#` would silently end the literal early. Every
/// character that could close or continue the literal is escaped, and the remaining control
/// characters go out as `\u{…}` so the generated file stays plain ASCII-safe text a reviewer can
/// read in a diff.
fn string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            '\0' => out.push_str("\\0"),
            other if other.is_control() => out.push_str(&format!("\\u{{{:x}}}", other as u32)),
            other => out.push(other),
        }
    }
    out.push('"');
    out
}

