//! `connectors.lock`, and the hash domain it records.
//!
//! Two properties are the whole story, and both are here as tests rather than as intentions:
//!
//! 1. **Unchanged inputs reproduce the file byte for byte.** `flux-connectors check` (C-14) is only
//!    worth running if a clean tree is silent, so anything that varies without an input changing —
//!    a timestamp, a map's iteration order, the order providers were discovered in — would make the
//!    tool cry wolf until someone turned it off.
//! 2. **Each hash covers exactly one input.** That is what lets `check` say *which* input moved.
//!
//! The fixture is Zendesk as `docs/designs/provider-operation-inventory.md` §3 records it, run
//! through the real [`provider::load`] front-end rather than a hand-built IR, so the hashes here are
//! the hashes a build would actually record.

use connector_spec::{provider, sha256_hex, Connector, LockEntry, Lockfile, Provenance};

// ---------------------------------------------------------------------------------------------
// The fixture, and a stand-in for the parts of the pipeline this crate does not own
// ---------------------------------------------------------------------------------------------

const ZENDESK_TOML: &str = r#"
id = "zendesk"
vendor = "Zendesk"
base_url = "https://acme.zendesk.com"
description = "Zendesk Support ticketing"
default_auth = [{ credentials = ["zendesk.api_token"] }]

[[auth]]
name = "zendesk.api_token"
scheme = "basic"
env = ["ZENDESK_API_TOKEN"]
user_env = ["ZENDESK_USER"]
user_suffix = "/token"

[[operations]]
id = "zendesk.ticket.show"
method = "GET"
direction = "read"
path = "/api/v2/tickets/{ticket_id}.json"
description = "Show one ticket"
risk = "low"
idempotency = "idempotent"

[[operations.params.path]]
name = "ticket_id"
required = true
schema = { type = "integer", format = "uint64", minimum = 1 }
"#;

const SPEC: &str = r#"{"openapi":"3.0.0","info":{"title":"Zendesk","version":"1.0.0"}}"#;

/// Where [`SPEC`] sits in the cache, spelled as the two fixtures below spell `[spec] path`.
const SPEC_PATH: &str = "specs/zendesk/1.0.0.json";

const GENERATOR: &str = "flux-connectors 0.1.0";

/// The committed bytes one build reads, plus the identity of the generator reading them — every
/// input `connectors.lock` claims to cover.
struct Inputs {
    definition: String,
    spec: Option<String>,
    generator: String,
}

impl Default for Inputs {
    fn default() -> Self {
        Self {
            definition: ZENDESK_TOML.to_string(),
            spec: Some(SPEC.to_string()),
            generator: GENERATOR.to_string(),
        }
    }
}

/// The fixture definition, compiled against a cache holding [`SPEC`] at [`SPEC_PATH`].
fn load(definition: &str) -> connector_spec::LoadedProvider {
    provider::load_with_spec(
        "providers/zendesk.toml",
        definition,
        &[connector_spec::SpecDocument {
            path: SPEC_PATH,
            document: SPEC,
        }],
    )
    .expect("load")
}

/// A stand-in for `connector-flux`, doing the one thing that matters here: an artifact is a
/// function of both the IR *and* the generator that emitted it, so a generator bump has to reach
/// the artifact hash. `crates/connector-cli/src/seam.rs` stamps exactly this header today.
fn emit(connector: &Connector, generator: &str) -> String {
    format!(
        "// Generated by {generator} — do not edit.\n{}\n",
        connector.hash_domain().expect("hash domain")
    )
}

/// One provider's full trip from committed bytes to a lockfile row, as `connector-cli` will make
/// it: load the TOML **against the spec cache**, hash the spec bytes that were read off disk, emit,
/// record.
///
/// The cache is passed whether or not the definition pins anything, exactly as `seam::load` passes
/// it — a directory holding a document is not a declaration, and the two fixtures here that *do*
/// declare `[spec]` are compiled rather than skeletonised (C-421).
fn entry(inputs: &Inputs) -> LockEntry {
    let loaded = load(&inputs.definition);
    let mut connector = loaded.connector;
    connector.provenance.spec_sha256 = inputs.spec.as_ref().map(|spec| sha256_hex(spec.as_bytes()));

    let module = emit(&connector, &inputs.generator);
    let document = document(&connector, &inputs.generator);
    LockEntry::for_connector(&connector, &inputs.generator)
        .expect("lock entry")
        .with_artifact("zendesk.flux", module.as_bytes())
        .with_artifact("catalog/zendesk.catalog.json", document.as_bytes())
}

/// A stand-in for the canonical catalog document (C-536), the way [`emit`] stands in for
/// `connector-flux`: the document is the *complete* published surface in one JSON file, which is
/// exactly why its bytes carry everything the lockfile must not — the resolved endpoint, the
/// credential names, the environment keys. Recording it is safe only because the row holds a path
/// and a hash; this fixture is what lets `the_lockfile_carries_no_credential_and_no_endpoint`
/// state that against the new rows rather than assume it.
fn document(connector: &Connector, generator: &str) -> String {
    format!(
        "{{\"generator\":{generator:?},\"connector\":{:?},\"base_url\":{:?},\"auth\":{}}}\n",
        connector.id,
        connector.base_url,
        serde_json::to_string(&connector.auth).expect("auth serializes"),
    )
}

/// The rendered lockfile for one set of inputs.
fn render(inputs: &Inputs) -> String {
    let mut lockfile = Lockfile::new();
    lockfile.insert(entry(inputs));
    lockfile.to_toml().expect("render")
}

/// A minimal connector, for the hash-domain tests that need to vary one field at a time.
fn bare(provenance: Provenance) -> Connector {
    Connector {
        id: "zendesk".into(),
        authority: None,
        runtime: connector_spec::Runtime::Http,
        api_version: None,
        services: Vec::new(),
        vendor: "Zendesk".into(),
        base_url: "https://acme.zendesk.com".into(),
        description: String::new(),
        auth: Vec::new(),
        default_auth: Vec::new(),
        operations: Vec::new(),
        events: Vec::new(),
        channels: Vec::new(),
        config: Vec::new(),
        verify: None,
        graphs: Vec::new(),
        provenance,
    }
}

