/// A lockfile is committed, reviewed in a diff, and kept forever. It carries hashes, ids and
/// versions — never a secret, and never a resolved endpoint. The spec's `source_url` is the one
/// URL it holds, and that is a published specification document, not a tenant's API.
#[test]
fn the_lockfile_carries_no_credential_and_no_endpoint() {
    let rendered = render(&Inputs {
        definition: format!(
            "{ZENDESK_TOML}\n\
             [spec]\n\
             path = \"{SPEC_PATH}\"\n\
             source_url = \"https://developer.zendesk.com/zendesk/oas.yaml\"\n"
        ),
        ..Inputs::default()
    });

    for forbidden in [
        // The endpoint the generated module calls, and the path it calls on it.
        "acme.zendesk.com",
        "/api/v2/tickets",
        // The credential's name, its scheme, and the environment keys that resolve it. None of
        // these is a secret on its own, and none of them belongs in a hash record either: the
        // lockfile's job is drift detection, and every name it prints is a name an attacker
        // reading the repo gets for free somewhere it is actually load-bearing.
        "zendesk.api_token",
        "ZENDESK_API_TOKEN",
        "ZENDESK_USER",
        "basic",
        "/token",
    ] {
        assert!(
            !rendered.contains(forbidden),
            "{forbidden:?} must never reach connectors.lock:\n{rendered}"
        );
    }

    // The specification URL is recorded, deliberately — C-14 re-fetches from it.
    assert!(rendered.contains("https://developer.zendesk.com/zendesk/oas.yaml"));

    // The canonical document's row (C-536) is the sharpest instance of the rule: the document's
    // own bytes carry the endpoint, the credential names and the environment keys — the fixture
    // above puts them there on purpose — and what reaches the lockfile is its path and its hash.
    assert!(
        rendered.contains("\"catalog/zendesk.catalog.json\""),
        "the document row must be recorded:\n{rendered}"
    );
}

