/// Editing the provider TOML moves its own hash, and the hashes of what it produced — never the
/// spec's, never the generator.
#[test]
fn a_changed_toml_moves_the_toml_hash_and_nothing_upstream_of_it() {
    let before = entry(&Inputs::default());

    let after = entry(&Inputs {
        definition: ZENDESK_TOML.replace("Show one ticket", "Show a single ticket"),
        ..Inputs::default()
    });

    assert_ne!(
        before.toml_sha256, after.toml_sha256,
        "the TOML bytes changed"
    );
    assert_ne!(
        before.ir_sha256, after.ir_sha256,
        "so did what they compile to"
    );
    assert_ne!(
        before.artifacts, after.artifacts,
        "and so did the artifacts"
    );
    assert_eq!(
        before.spec_sha256, after.spec_sha256,
        "the spec did not move"
    );
    assert_eq!(before.generator, after.generator, "nor did the generator");
}

/// The sharp end of excluding provenance from the hash domain: a comment-only edit changes the
/// file's bytes and *nothing else*. `check` reports the TOML as edited, and does not claim the
/// generated artifacts went stale — because they did not.
#[test]
fn a_comment_only_edit_moves_the_toml_hash_alone() {
    let before = entry(&Inputs::default());

    let after = entry(&Inputs {
        definition: format!("# a note for the next reader\n{ZENDESK_TOML}"),
        ..Inputs::default()
    });

    assert_ne!(before.toml_sha256, after.toml_sha256);
    assert_eq!(
        before.ir_sha256, after.ir_sha256,
        "a comment compiles to nothing, so the IR hash must not move"
    );
    assert_eq!(before.artifacts, after.artifacts);
}

/// A new vendored spec moves the spec hash. Nothing else moves *here* because this fixture builds
/// its IR from the TOML alone — the two columns are independent by construction. Now that ingest
/// exists (C-4), a spec change that touches a **selected** operation moves `ir_sha256` too, which is
/// correct and is exactly what the separate columns are for: a document that moved and an IR that
/// did not is a vendor edit nothing this connector selected.
#[test]
fn a_changed_spec_moves_the_spec_hash() {
    let before = entry(&Inputs::default());

    let after = entry(&Inputs {
        spec: Some(SPEC.replace("1.0.0", "1.1.0")),
        ..Inputs::default()
    });

    assert_ne!(before.spec_sha256, after.spec_sha256);
    assert_eq!(before.toml_sha256, after.toml_sha256);
    assert_eq!(before.generator, after.generator);
}

/// A generator bump invalidates generated output — that is the point of recording it — and must
/// invalidate nothing else. None of the inputs moved, so none of the input hashes may.
#[test]
fn a_changed_generator_moves_the_artifact_hashes_alone() {
    let before = entry(&Inputs::default());

    let after = entry(&Inputs {
        generator: "flux-connectors 0.2.0".to_string(),
        ..Inputs::default()
    });

    assert_ne!(before.generator, after.generator);
    assert_ne!(
        before.artifacts, after.artifacts,
        "a generator bump must invalidate the artifacts it produced"
    );
    assert_eq!(before.toml_sha256, after.toml_sha256);
    assert_eq!(before.spec_sha256, after.spec_sha256);
    assert_eq!(
        before.ir_sha256, after.ir_sha256,
        "the IR is what the inputs mean, and the inputs did not change"
    );
}

