/// Rebuilding one provider replaces its row rather than appending a second one, and the rows stay
/// ordered by provider id however they arrived.
#[test]
fn a_rebuild_replaces_a_row_rather_than_duplicating_it() {
    let mut lockfile = Lockfile::new();
    for id in ["zendesk", "ollama", "zendesk", "freshdesk"] {
        let mut connector = bare(Provenance::default());
        connector.id = id.into();
        lockfile.insert(LockEntry::for_connector(&connector, GENERATOR).expect("entry"));
    }

    let ids: Vec<&str> = lockfile.entries().iter().map(|e| e.id.as_str()).collect();
    assert_eq!(ids, ["freshdesk", "ollama", "zendesk"]);
    assert!(lockfile.entry("ollama").is_some());
    assert!(lockfile.entry("shopify").is_none());
}

/// C-25 will record **two** hashes for the babelforce spec — what upstream served, and the scrubbed
/// copy this repo may legally vendor. That has to be an added field, not a reshaped entry: absent
/// everywhere it does not apply, present and round-tripping where it does.
#[test]
fn a_second_spec_hash_is_additive() {
    let connector = bare(Provenance {
        spec_sha256: Some("a".repeat(64)),
        ..Provenance::default()
    });
    let plain = LockEntry::for_connector(&connector, GENERATOR).expect("entry");
    assert_eq!(plain.upstream_spec_sha256, None);

    let scrubbed = LockEntry::for_connector(&connector, GENERATOR)
        .expect("entry")
        .with_upstream_spec_sha256("c".repeat(64));

    let mut lockfile = Lockfile::new();
    lockfile.insert(plain.clone());
    let without = lockfile.to_toml().expect("render");
    assert!(
        !without.contains("upstream_spec_sha256"),
        "the second hash must not clutter every other provider's row"
    );

    let mut lockfile = Lockfile::new();
    lockfile.insert(scrubbed.clone());
    let with = lockfile.to_toml().expect("render");
    assert!(with.contains(&format!("upstream_spec_sha256 = \"{}\"", "c".repeat(64))));
    assert_eq!(
        Lockfile::parse(&with).expect("parse").entry("zendesk"),
        Some(&scrubbed),
    );
    // And it is genuinely additive: dropping it recovers the plain row exactly.
    assert_eq!(
        Lockfile::parse(&without).expect("parse").entry("zendesk"),
        Some(&plain),
    );
}

/// A lockfile from a future format version is refused rather than misread — a silently
/// misinterpreted file would report drift in every provider at once, which reads as a broken tool
/// rather than as the version mismatch it is.
#[test]
fn a_lockfile_from_another_format_version_is_refused() {
    let rendered = render(&Inputs::default());
    let future = rendered.replace(
        &format!("version = {}", connector_spec::LOCKFILE_VERSION),
        &format!("version = {}", connector_spec::LOCKFILE_VERSION + 1),
    );

    let error = Lockfile::parse(&future).expect_err("a future version must be refused");
    let message = error.to_string();
    assert!(message.contains("version"), "{message}");
    assert!(message.contains("connectors.lock"), "{message}");
}

/// The lockfile is as strict as the IR types, and for the same reason: a key nobody recognizes is
/// either a typo in a hand-edit or a field from a version this build cannot honor, and discarding
/// it silently would mean verifying less than the file claims to record.
#[test]
fn an_unknown_key_is_refused() {
    let rendered = render(&Inputs::default());
    let tampered = rendered.replace("ir_sha256 = ", "ir_sha256_typo = ");

    let error = Lockfile::parse(&tampered).expect_err("an unknown key must be refused");
    assert!(error.to_string().contains("ir_sha256_typo"), "{error}");
}
